import {build} from 'esbuild';
import {mkdir,readFile,writeFile,cp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const result=await build({entryPoints:[resolve(root,'src/app.js')],bundle:true,format:'iife',target:['es2020'],minify:true,write:false,legalComments:'inline'});
let html=await readFile(resolve(root,'src/index.html'),'utf8');
const css=await readFile(resolve(root,'src/style.css'),'utf8'),license=await readFile(resolve(root,'src/vendor/THREE-LICENSE.txt'),'utf8');
const style='<link rel="stylesheet" href="./style.css">',script='<script type="module" src="./app.js"></script>';
if(!html.includes(style)||!html.includes(script))throw new Error('Inline build insertion points are missing');
html=html.replace(style,()=>`<style>${css}</style>`).replace(script,()=>`<script>${result.outputFiles[0].text.replaceAll('</script','<\\/script')}</script>`);
html=html.replace('<html lang="zh-CN">',`<!-- Three.js r160 / OrbitControls — MIT license\n${license}\n-->\n<html lang="zh-CN">`);
if(/<(script|link)[^>]+(?:src|href)=["'](?:https?:|\/\/|\.\/)/.test(html))throw new Error('Runtime dependency was left external');
await mkdir(resolve(root,'dist'),{recursive:true});
await writeFile(resolve(root,'dist/index.html'),html);
await writeFile(resolve(root,'电脑主机拆装实训.html'),html);
await writeFile(resolve(root,'index.html'),html);
await cp(resolve(root,'src/vendor/THREE-LICENSE.txt'),resolve(root,'dist/THREE-LICENSE.txt'));
console.log(`Built PC LAB: ${Buffer.byteLength(html).toLocaleString()} bytes, all runtime code/CSS/geometry inline; no external runtime assets.`);
